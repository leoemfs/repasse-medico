// Teste do menu: recolher/expandir (☰ e Ctrl+B), memória da escolha, dica e janela estreita (sem modo celular).
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const raiz = new URL('..', import.meta.url).pathname, out = raiz + 'test/saida/';
const html = 'file://' + raiz + 'dist/' + fs.readdirSync(raiz + 'dist').find(f => f.startsWith('Repasse_Medico_v'));
const b = await chromium.launch(), erros = [];
const ok = (cond, msg) => { console.log((cond ? '✔ ' : '✘ ') + msg); if (!cond) process.exitCode = 1; };
const p = await (await b.newContext({ viewport: { width: 1366, height: 820 } })).newPage();
p.on('pageerror', e => erros.push(e.message));
await p.goto(html + '#inicio'); await p.waitForFunction(() => window.__RM);
const larg = () => p.evaluate(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width));
ok(await larg() === 232, 'abre aberto (232 px)');
await p.screenshot({ path: out + 'menu_aberto.png' });
await p.click('#btnMenu');
ok(await larg() === 64, 'botão ☰ recolhe (64 px)');
ok(await p.getAttribute('#btnMenu', 'aria-expanded') === 'false', 'aria-expanded = false');
await p.hover('.nav a[data-pag="equivalencias"]');
ok(await p.isVisible('.nav a[data-pag="equivalencias"] .dica'), 'dica aparece ao passar o mouse');
await p.screenshot({ path: out + 'menu_recolhido.png' });
await p.click('.nav a[data-pag="bases"]'); await p.waitForFunction(() => document.getElementById('titulo').textContent === 'Bases e regras', null, { timeout: 3000 }).catch(() => {});
ok(await p.textContent('#titulo') === 'Bases e regras', 'ícone recolhido funciona como atalho');
await p.reload(); await p.waitForFunction(() => window.__RM, null, { polling: 200, timeout: 30000 });
ok(await larg() === 64, 'escolha lembrada após recarregar');
await p.keyboard.press('Control+b');
ok(await larg() === 232, 'Ctrl+B expande');
await p.keyboard.press('Control+b');
ok(await larg() === 64, 'Ctrl+B recolhe');
// v3.0.0-alpha.12: sem modo celular (decisão do usuário, P3 da auditoria). Janela estreita no computador: o mesmo menu.
// v3.0.0-alpha.27 (pedido de 24/11, no celular): em tela estreita o menu começa recolhido (só ícones); o ☰ abre.
const m = await (await b.newContext({ viewport: { width: 700, height: 800 } })).newPage();
m.on('pageerror', e => erros.push(e.message));
await m.goto(html + '#inicio'); await m.waitForFunction(() => window.__RM);
const estreita = await m.evaluate(() => ({ barra: !!document.querySelector('.barra-cel,#barraCel,#veuGaveta,.gaveta-cab'), larg: Math.round(document.querySelector('.sidebar').getBoundingClientRect().width), abas: [...document.querySelectorAll('.nav a[data-pag]')].filter(a => a.offsetParent).length }));
ok(!estreita.barra && estreita.larg === 64 && estreita.abas === 7, `janela estreita: mesmo menu lateral, começa recolhido (só ícones), sem gaveta nem barra inferior (${JSON.stringify(estreita)})`);
const sobra = await m.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1);
ok(sobra, 'janela estreita: a página não rola para o lado');
await m.click('#btnMenu');
ok(Math.round(await m.evaluate(() => document.querySelector('.sidebar').getBoundingClientRect().width)) === 232, 'na janela estreita, ☰ abre o menu');
await m.screenshot({ path: out + 'menu_estreito.png' });
ok(!erros.length, 'sem erros no console' + (erros.length ? ': ' + erros.join(' | ') : ''));
await b.close();
