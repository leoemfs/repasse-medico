// Teste do menu: recolher/expandir (☰ e Ctrl+B), memória da escolha, dica e barra do celular.
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const raiz = new URL('..', import.meta.url).pathname, out = raiz + 'test/saida/';
const html = 'file://' + raiz + 'dist/' + fs.readdirSync(raiz + 'dist').find(f => f.startsWith('Repasse_Medico_v'));
const b = await chromium.launch(), erros = [];
const ok = (cond, msg) => { console.log((cond ? '✔ ' : '✘ ') + msg); if (!cond) process.exitCode = 1; };
const p = await (await b.newContext({ viewport: { width: 1366, height: 820 } })).newPage();
p.on('pageerror', e => erros.push(e.message));
await p.goto(html + '#inicio'); await p.waitForFunction(() => window.__RM);
const larg = () => p.evaluate(() => Math.round(document.querySelector('.sidebar').getBoundingClientRect().width));
ok(await larg() === 232, 'abre aberto (232 px)');
await p.screenshot({ path: out + 'menu_aberto.png' });
await p.click('#btnMenu');
ok(await larg() === 64, 'botão ☰ recolhe (64 px)');
ok(await p.getAttribute('#btnMenu', 'aria-expanded') === 'false', 'aria-expanded = false');
await p.hover('.nav a[data-pag="equivalencias"]');
ok(await p.isVisible('.nav a[data-pag="equivalencias"] .dica'), 'dica aparece ao passar o mouse');
await p.screenshot({ path: out + 'menu_recolhido.png' });
await p.click('.nav a[data-pag="bases"]'); await p.waitForFunction(() => document.getElementById('titulo').textContent === 'Bases', null, { timeout: 3000 }).catch(() => {});
ok(await p.textContent('#titulo') === 'Bases', 'ícone recolhido funciona como atalho');
await p.reload(); await p.waitForFunction(() => window.__RM);
ok(await larg() === 64, 'escolha lembrada após recarregar');
await p.keyboard.press('Control+b');
ok(await larg() === 232, 'Ctrl+B expande');
await p.keyboard.press('Control+b');
ok(await larg() === 64, 'Ctrl+B recolhe');
const m = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
m.on('pageerror', e => erros.push(e.message));
await m.goto(html + '#inicio'); await m.waitForFunction(() => window.__RM);
const barra = await m.evaluate(() => { const r = document.querySelector('.nav').getBoundingClientRect(); return { y: Math.round(r.bottom), h: Math.round(r.height), n: [...document.querySelectorAll('.nav .curto')].filter(e => e.offsetParent).length, hamb: !!document.getElementById('btnMenu').offsetParent }; });
ok(barra.y === 844 && barra.n === 8 && !barra.hamb, `barra fixa no rodapé com 8 atalhos e sem ☰ (${JSON.stringify(barra)})`);
await m.tap('.nav a[data-pag="correcao"]'); await m.waitForFunction(() => document.getElementById('titulo').textContent !== 'Início', null, { timeout: 3000 }).catch(() => {});
ok(await m.textContent('#titulo') === 'Correção de prestador', 'toque na barra navega');
ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'sem rolagem horizontal');
await m.goto(html + '#inicio'); await m.waitForTimeout(200);
await m.screenshot({ path: out + 'menu_celular.png' });
ok(!erros.length, 'sem erros no console' + (erros.length ? ': ' + erros.join(' | ') : ''));
await b.close();
