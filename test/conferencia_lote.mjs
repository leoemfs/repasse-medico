// Vários PDFs (de vários prestadores, unidades e grupos) com os arquivos reais da competência 10/2026 (dados/comp_10-2026):
// o seletor de relatórios da Conferência filtra por unidade e grupo, a unidade acompanha o relatório e o lote confere os filtrados.
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const raiz = new URL('..', import.meta.url).pathname, pasta = raiz + 'dados/comp_10-2026/', d = f => raiz + 'dados/' + f;
const html = 'file://' + raiz + 'dist/' + fs.readdirSync(raiz + 'dist').find(f => f.startsWith('Repasse_Medico_v'));
const b = await chromium.launch(), erros = [];
const ok = (cond, msg) => { console.log((cond ? '✔ ' : '✘ ') + msg); if (!cond) process.exitCode = 1; };
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
await p.clock.install({ time: new Date('2026-10-30T10:00:00') });
p.on('pageerror', e => erros.push(e.message)); p.on('console', m => { if (m.type() === 'error') erros.push(m.text()); });
await p.addInitScript(() => localStorage.setItem('rm2.operador', JSON.stringify('Teste Lote')));
await p.goto(html + '#inicio');
await p.waitForFunction(() => document.getElementById('stInit').textContent.includes('Pronto'), null, { timeout: 30000 });
const okDlg = async () => { await p.waitForSelector('#dlg[open]'); await p.click('#dlgBotoes button[value=ok]'); await p.waitForFunction(() => !document.getElementById('dlg').open); await p.waitForTimeout(250); };
await p.goto(html + '#bases'); await p.waitForSelector('[data-bsub]'); await p.click('[data-bsub="prestadores"]');
await p.setInputFiles('#prCtrlArq', d('repasse_10-2026_controle.xlsx')); await okDlg();
const pdfs = fs.readdirSync(pasta).filter(f => f.endsWith('.pdf') && !/CORRECAO/.test(f)).sort();
await p.goto(html + '#inicio'); await p.setInputFiles('#inMV', pdfs.map(f => pasta + f)); await p.waitForFunction(n => window.__RM.S.relatorios.length === n, pdfs.length, { timeout: 300000 });
await p.setInputFiles('#inApolo', pasta + 'APOLO_10-2026_ref_09-2026.xlsx'); await p.waitForFunction(() => !!window.__RM.S.apolo, null, { timeout: 300000 });
while (await p.isVisible('#dlg[open]')) await okDlg();
await p.goto(html + '#conferencia'); await p.waitForSelector('#cfFUn');
await p.selectOption('#cfFUn', '17'); await p.waitForSelector('#cfFGr'); await p.selectOption('#cfFGr', 'usg'); await p.waitForTimeout(300);
const ops = await p.$$eval('#cfRel option', o => o.map(x => x.textContent));
const esperado = pdfs.filter(f => /USG_.*_un17/.test(f)).length;
ok(ops.length === esperado && ops.every(t => /unidade 17 USG/.test(t)), `filtro unidade 17 + USG: ${ops.length} relatório(s) (${esperado} PDFs de USG da unidade 17)`);
ok(await p.inputValue('#cfUn') === '17', 'a unidade dos laudos já vem 17');
await p.selectOption('#cfFUn', '*'); await p.selectOption('#cfFGr', '*'); await p.waitForTimeout(200);
const v3 = await p.$$eval('#cfRel option', o => o.find(x => /unidade 5/.test(x.textContent))?.value);
await p.selectOption('#cfRel', v3); await p.waitForTimeout(200);
ok(await p.inputValue('#cfUn') === '5', 'trocar para um relatório da unidade 5 troca a unidade dos laudos para 5');
await p.selectOption('#cfFUn', '17'); await p.selectOption('#cfFGr', 'usg'); await p.waitForTimeout(200);
const n0 = await p.evaluate(() => window.__RM.S.rodadas.length);
await p.click('[data-cflote]'); await okDlg();
await p.waitForFunction(n => window.__RM.S.rodadas.length >= n, n0 + esperado, { timeout: 300000 });
const rod = await p.evaluate(n => window.__RM.S.rodadas.slice(n).map(r => `${r.prestadorCod}|${r.unidadeCod}`), n0);
ok(rod.length === esperado && rod.every(r => r.endsWith('|17')), `«Conferir os ${esperado} relatórios filtrados»: uma rodada para cada, todas na unidade 17 (${rod.join(', ')})`);
ok(!erros.length, 'sem erros no console' + (erros.length ? ': ' + [...new Set(erros)].slice(0, 3).join(' | ') : ''));
await b.close();
